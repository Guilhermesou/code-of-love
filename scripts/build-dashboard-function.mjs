import { readFile, mkdir, writeFile } from 'node:fs/promises';

// Keep the dashboard copy in sync with the same modules used by the app and tests.
const root = new URL('../', import.meta.url);
const files = [
  'public/music.js',
  'public/game-model.js',
  'public/model.js',
  'public/lib/slug.js',
  'public/lib/media.js',
  'supabase/functions/shared-surprise/handler.js',
];
const sections = [];
for (const file of files) {
  const source = await readFile(new URL(file, root), 'utf8');
  sections.push(`// Source: ${file}\n${source.replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '')}`);
}
const entry = (await readFile(new URL('supabase/functions/shared-surprise/index.ts', root), 'utf8'))
  .replace(/^import .*;\r?\n/gm, '')
  .replaceAll("Deno.env.get('SUPABASE_URL')!", "Deno.env.get('SUPABASE_URL')")
  .replaceAll("Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!", "Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')");
await mkdir(new URL('supabase/dashboard/', root), { recursive: true });
await writeFile(new URL('supabase/dashboard/shared-surprise.js', root),
  '// Generated by node scripts/build-dashboard-function.mjs. Do not edit directly.\n'
  + "import { createClient } from 'npm:@supabase/supabase-js@2';\n\n"
  + sections.join('\n\n') + '\n\n' + entry);
console.log('Generated supabase/dashboard/shared-surprise.js');
